/* copied from trigger_jointer plugin
 * forwards the event to all sinkpads, takes ownership of the event
 */

typedef struct {
    GstEvent *event;
    gboolean flush;
} EventData;

static gboolean
  forward_src_event_func(GstPad *pad, GValue *ret, EventData *data) {
    GST_DEBUG_OBJECT(pad, "forward an event");
    gst_event_ref(data->event);
    if (!gst_pad_push_event(pad, data->event)) {
        /* quick hack to unflush the pads. ideally we need  a way
         * to just unflush this single collect pad */
        if (data->flush) gst_pad_send_event(pad, gst_event_new_flush_stop());
    } else {
        g_value_set_boolean(ret, TRUE);
    }
    gst_object_unref(GST_OBJECT(pad));
    return TRUE;
}

static gboolean
  forward_src_event(TriggerJointer *jointer, GstEvent *event, gboolean flush) {
    GstIterator *it;
    GValue vret    = { 0 };
    EventData data = { event, flush };
    gboolean success;

    g_value_init(&vret, G_TYPE_BOOLEAN);
    g_value_set_boolean(&vret, FALSE);

    it = gst_element_iterate_sink_pads(GST_ELEMENT(jointer));
    while (TRUE) {
        switch (gst_iterator_fold(
          it, (GstIteratorFoldFunction)forward_src_event_func, &vret, &data)) {
        case GST_ITERATOR_RESYNC:
            gst_iterator_resync(it);
            g_value_set_boolean(&vret, TRUE);
            break;

        case GST_ITERATOR_OK:
        case GST_ITERATOR_DONE: success = g_value_get_boolean(&vret); goto done;

        default: success = FALSE; goto done;
        }
    }
done:
    gst_iterator_free(it);
    gst_event_unref(event);

    return success;
}

/*
 * handle events received on the source pad
 */

static gboolean src_event(GstPad *pad, GstEvent *event) {
    TriggerJointer *jointer = TRIGGER_JOINTER(gst_pad_get_parent(pad));
    gboolean success;

    switch (GST_EVENT_TYPE(event)) {
    case GST_EVENT_SEEK: {
        gdouble rate;
        GstSeekFlags flags;
        GstSeekType curtype, endtype;
        gint64 cur, end;
        gboolean flush;

        gst_event_parse_seek(event, &rate, NULL, &flags, &curtype, &cur,
                             &endtype, &end);
        flush = flags & GST_SEEK_FLAG_FLUSH;

        /* FIXME:  copy the adder's logic re flushing */

        success = forward_src_event(jointer, event, flush);
        break;
    }

    /* events that can't be handled */
    case GST_EVENT_QOS:
    case GST_EVENT_NAVIGATION:
        gst_event_unref(event);
        success = FALSE;
        break;

    /* forward the rest out all sink pads */
    default:
        GST_DEBUG_OBJECT(jointer, "forward src event");
        success = forward_src_event(jointer, event, FALSE);
        break;
    }

    return success;
}

static GstStateChangeReturn
  trigger_jointer_change_state(GstElement *element, GstStateChange transition) {
    TriggerJointer *jointer = TRIGGER_JOINTER(element);

    switch (transition) {
    case GST_STATE_CHANGE_NULL_TO_READY: break;

    case GST_STATE_CHANGE_READY_TO_PAUSED:
        gst_collect_pads_start(jointer->collect);
        break;

    case GST_STATE_CHANGE_PAUSED_TO_PLAYING: break;

    case GST_STATE_CHANGE_PAUSED_TO_READY:
        /* need to unblock the collectpads before calling the
         * parent change_state so that streaming can finish */
        gst_collect_pads_stop(jointer->collect);
        break;

    default: break;
    }

    return GST_ELEMENT_CLASS(parent_class)->change_state(element, transition);
}

static void destroy_notify(TriggerJointerCollectData *data) {
    if (data) {
        if (data->ifo_name) free(data->ifo_name);
        if (data->adapter) {
            gst_adapter_clear(data->adapter);
            g_object_unref(data->adapter);
            data->adapter = NULL;
        }
        if (data->flag_segments) {
            g_array_unref(data->flag_segments);
            data->flag_segments = NULL;
        }
    }
}

static GstClockTime get_timelag(gchar *ifo) {
    if (strncmp(ifo, "V1", IFO_LEN) == 0) return V1_TIMELAG;
    else if (strncmp(ifo, "K1", IFO_LEN) == 0)
        return K1_TIMELAG;
    else
        return -1;
}

static gboolean trigger_jointer_padding_adapter(TriggerJointerCollectData *data,
                                                guint zerobuf_size) {
    GstBuffer *zerobuf = gst_buffer_new_and_alloc(zerobuf_size);
    memset(GST_BUFFER_DATA(zerobuf), 0, GST_BUFFER_SIZE(zerobuf));
    gst_adapter_push(data->adapter, zerobuf);
    return TRUE;
}

static gboolean trigger_jointer_set_snr_info(TriggerJointer *jointer) {
    GList *snrdata;
    GstCaps *caps;
    GstStructure *s;
    GstPad *this_pad;
    TriggerJointerCollectData *data;
    GstClockTime ori_timelag;

    for (snrdata = jointer->collect_snrdata; snrdata;
         snrdata = g_slist_next(snrdata)) {
        data = snrdata->data;

        /* data->data is the GstCollectData, it has its managed pad */
        this_pad = (GstPad *)((data->data).pad);
        caps     = GST_PAD_CAPS(this_pad);
        GST_DEBUG_OBJECT(data, "getting caps on pad %p of %s: %" GST_PTR_FORMAT,
                         this_pad, GST_PAD_NAME(this_pad), caps);

        /* get the caps out */
        s = gst_caps_get_structure(caps, 0);
        gst_structure_get_int(s, "width", &data->width);
        gst_structure_get_int(s, "rate", &data->rate);
        gst_structure_get_int(s, "channels", &data->channels);

        /* bytes per sample */
        data->bps    = (data->width / 8) * data->channels;
        data->ntmplt = data->channels / 2;
        /* original timelag read from find_timedelay.py in nano seconds */
        ori_timelag = get_timelag(data->ifo_name);
        if (ori_timelag == -1) {
            fprintf(stderr,
                    "Can not get max time lag of this detector, exiting\n");
            exit(0);
        }
        /* timelag in number of samples */
        data->ntimelag = floor(ori_timelag / (double)GST_SECOND * data->rate);
        /* timelag in nano seconds (GstClockTime) */
        data->timelag = data->ntimelag / (double)data->rate * GST_SECOND;
        GST_DEBUG_OBJECT(
          data,
          "get ifo_name %s, ifo_mapping %d, rate %d, channels %d, bps %d,"
          "timelag in nsamples %d",
          data->ifo_name, data->ifo_mapping, data->rate, data->channels,
          data->bps, data->ntimelag);
    }
    return TRUE;
}

static GstPad *trigger_jointer_request_new_pad(GstElement *element,
                                               GstPadTemplate *templ,
                                               const gchar *req_name) {
    TriggerJointer *jointer = TRIGGER_JOINTER(element);

    /* create the pad */
    GstPad *newpad;
    newpad = gst_pad_new_from_template(templ, req_name);

    /* add the newpad to the element */
    if (!gst_element_add_pad(element, newpad)) {
        gst_object_unref(newpad);
        GST_DEBUG_OBJECT(element, "add %s pad faied", req_name);
        return NULL;
    }

    /* add the new pad to the collect pads in a default way, so the pad's event
     * is dealt with */
    TriggerJointerCollectData *data;
    data = (TriggerJointerCollectData *)gst_collect_pads_add_pad_full(
      jointer->collect, newpad, sizeof(TriggerJointerCollectData),
      (GstCollectDataDestroyNotify)GST_DEBUG_FUNCPTR(destroy_notify));

    if (!data) {
        gst_element_remove_pad(element, newpad);
        GST_DEBUG_OBJECT(element, "get the collect data faied for %s",
                         req_name);
        gst_object_unref(newpad);
        return NULL;
    }
    /* alignment flag for start time */
    data->is_aligned = FALSE;

    int j;
    /* new pad data: check if the data is snr series or table */
    if (strlen(req_name) == SNR_PAD_NAME_LEN) {
        jointer->collect_snrdata =
          g_slist_append(jointer->collect_snrdata, data);
        data->is_snr = TRUE;
        /* adapter to store the SNR series */
        data->adapter = gst_adapter_new();
        /* gap segments */
        data->flag_segments = g_array_new(FALSE, FALSE, sizeof(FlagSegment));
        data->ifo_name      = (gchar *)malloc(IFO_LEN * sizeof(gchar));
        strncpy(data->ifo_name, req_name + 4,
                sizeof(data->ifo_name)); // 4 for snr_
        for (j = 0; j < MAX_NIFO; j++) {
            if (strncmp(data->ifo_name, IFOMap[j].name, IFO_LEN) == 0)
                data->ifo_mapping = j;
        }
    } else {
        jointer->collect_postcohdata = data;
        data->is_snr                 = FALSE;
        GST_DEBUG_OBJECT(element, "set postcoh collect data");
    }

    GST_DEBUG_OBJECT(
      element, "new pad for %s is added and initialized, it is %s SNR series",
      req_name, data->is_snr ? "a" : "NOT");
    return GST_PAD(newpad);
}

/* release the new pad when pipeline stops */
static void trigger_jointer_release_pad(GstElement *element, GstPad *pad) {
    TriggerJointer *jointer = TRIGGER_JOINTER(element);
    /* remove from collect pads */
    gst_collect_pads_remove_pad(jointer->collect, pad);
    /* remove from snr pads */
    jointer->collect_snrdata = g_slist_remove(jointer->collect_snrdata, pad);
    /* remove from element */
    gst_element_remove_pad(element, pad);
    /* free data->ifo_name */
}

/* get the time from the postcoh table pad for synchronization */
static gboolean trigger_jointer_get_start_end_time(GstCollectPads *pads,
                                                   TriggerJointer *jointer,
                                                   GstClockTime *tstart,
                                                   GstClockTime *tend,
                                                   gboolean *is_t0_set) {
    GList *collectlist;
    TriggerJointerCollectData *data;
    GstBuffer *buf;
    *tstart = GST_CLOCK_TIME_NONE;
    *tend   = GST_CLOCK_TIME_NONE;
    GstClockTime t_start_cur;
    gboolean is_t0_by_snr;

    for (collectlist = pads->data; collectlist;
         collectlist = g_slist_next(collectlist)) {
        data = collectlist->data;
        buf  = gst_collect_pads_peek(pads, (GstCollectData *)data);
        /* eos */
        if (!buf) {
            GST_ERROR_OBJECT(pads, "%s pad:EOS", data->ifo_name);
            gst_buffer_unref(buf);
            return FALSE;
        }
        /* invalid offset */
        if (!GST_BUFFER_OFFSET_IS_VALID(buf)
            || !GST_BUFFER_OFFSET_END_IS_VALID(buf)) {
            GST_ERROR_OBJECT(pads,
                             "%" GST_PTR_FORMAT ": %" GST_PTR_FORMAT
                             " does not have valid offsets",
                             ((GstCollectData *)data)->pad, buf);
            gst_buffer_unref(buf);
            return FALSE;
        }
        /* invalid timestamp */
        if (!GST_BUFFER_TIMESTAMP_IS_VALID(buf)
            || !GST_BUFFER_DURATION_IS_VALID(buf)) {
            GST_ERROR_OBJECT(
              jointer,
              "%" GST_PTR_FORMAT ": %" GST_PTR_FORMAT
              " does not have a valid timestamp and/or duration",
              ((GstCollectData *)jointer->collect_postcohdata)->pad, buf);
            gst_buffer_unref(buf);
            return FALSE;
        }

        t_start_cur = GST_BUFFER_TIMESTAMP(buf);

        if (*tstart == GST_CLOCK_TIME_NONE) {
            *tstart      = t_start_cur;
            *tend        = t_start_cur + GST_BUFFER_DURATION(buf);
            is_t0_by_snr = data->is_snr;
        } else {
            if (*tstart < t_start_cur) {
                *tstart      = t_start_cur;
                *tend        = t_start_cur + GST_BUFFER_DURATION(buf);
                is_t0_by_snr = data->is_snr;
            }
        }
        gst_buffer_unref(buf);
    }
    /* sanity check */
    g_assert(*tstart != GST_CLOCK_TIME_NONE);

    GstFlowReturn ret = GST_FLOW_OK;
    if (is_t0_by_snr) {
        /* push postcoh buffer downstream */
        /* get the tstart from the current postcoh buffer queued in postcoh
         * pad
         */
        buf = gst_collect_pads_pop(
          jointer->collect, (GstCollectData *)jointer->collect_postcohdata);
        ret        = gst_pad_push(jointer->srcpad, buf);
        *is_t0_set = FALSE;
        return ret;
    } else {
        *is_t0_set = TRUE;
        return TRUE;
    }
}

static gboolean trigger_jointer_align_collected(GstCollectPads *pads,
                                                TriggerJointer *jointer) {

    GSList *collectlist;
    TriggerJointerCollectData *data;
    GstBuffer *buf, *subbuf;
    GstClockTime t_cur, t_end_cur;
    gboolean all_aligned = TRUE, is_gap;
    guint64 offset_cur, offset_end_cur, buf_aligned_offset0;
    GstClockTime t0 = jointer->t0;

    GST_DEBUG_OBJECT(pads, "begin to align to t0 %" GST_TIME_FORMAT,
                     GST_TIME_ARGS(t0));

    for (collectlist = pads->data; collectlist;
         collectlist = g_slist_next(collectlist)) {
        data = collectlist->data;
        if (data->is_aligned) {
            /* do not collect the buffer in this pad. wait for other pads to
             * be aligned */
            // buf = gst_collect_pads_pop(pads, (GstCollectData *)data);
            // gst_adapter_push(data->adapter, buf);
            GST_DEBUG_OBJECT(data, "already aligned %s",
                             data->is_snr ? "SNR pad" : "postcoh pad");
            continue;
        }
        /* postcoh table buffer, set TRUE to is_aligned */
        if (data->is_snr == FALSE && data->is_aligned == FALSE) {
            GST_DEBUG_OBJECT(data, "set postcoh pad to aligned");
            data->is_aligned = TRUE;
            continue;
        }

        /* only align buffers from snr pads to the t0 from the postcoh pad
         * buffer */
        buf            = gst_collect_pads_pop(pads, (GstCollectData *)data);
        t_cur          = GST_BUFFER_TIMESTAMP(buf);
        t_end_cur      = t_cur + GST_BUFFER_DURATION(buf);
        offset_cur     = GST_BUFFER_OFFSET(buf);
        offset_end_cur = GST_BUFFER_OFFSET_END(buf);
        double offset_per_nanosecond = (double)data->rate / GST_SECOND;

        if (t_end_cur > t0) {

            /* padding the adapters in the SNR pads with zeros to account
             * for history data */
            guint zerobuf_size = data->ntimelag * data->bps;
            /* padding a zero buffer for history data */
            if (!trigger_jointer_padding_adapter(data, zerobuf_size)) {
                /* can not push to each pad adapter */
                GST_ERROR_OBJECT(jointer, "cannot push a zero buffer to each "
                                          "pad adapter, check adapter");
                return GST_FLOW_ERROR;
            }

            buf_aligned_offset0 = (guint)((t0 - t_cur) * offset_per_nanosecond);
            GST_DEBUG_OBJECT(
              pads,
              "buffer aligned offset0 %" G_GUINT64_FORMAT ", with timestamp "
              "%" GST_TIME_FORMAT ", duration %" GST_TIME_FORMAT
              ", offset %" G_GUINT64_FORMAT ", offset_end %" G_GUINT64_FORMAT,
              buf_aligned_offset0, GST_TIME_ARGS(GST_BUFFER_TIMESTAMP(buf)),
              GST_TIME_ARGS(GST_BUFFER_DURATION(buf)), GST_BUFFER_OFFSET(buf),
              GST_BUFFER_OFFSET_END(buf));

            g_assert(buf_aligned_offset0 >= 0);
            guint64 sub_size =
              (offset_end_cur - offset_cur - buf_aligned_offset0) * data->bps;
            subbuf = gst_buffer_create_sub(buf, buf_aligned_offset0, sub_size);
            g_assert(subbuf);

            GST_LOG_OBJECT(
              pads,
              "Created sub buffer of (%lu bytes) with timestamp "
              "%" GST_TIME_FORMAT ", duration %" GST_TIME_FORMAT
              ", offset %" G_GUINT64_FORMAT ", offset_end %" G_GUINT64_FORMAT,
              sub_size, GST_TIME_ARGS(GST_BUFFER_TIMESTAMP(subbuf)),
              GST_TIME_ARGS(GST_BUFFER_DURATION(subbuf)),
              GST_BUFFER_OFFSET(subbuf), GST_BUFFER_OFFSET_END(subbuf));

            gst_adapter_push(data->adapter, subbuf);

            data->is_aligned = TRUE;
            gst_buffer_unref(buf);
        } else {
            all_aligned = FALSE;
            GST_DEBUG_OBJECT(
              jointer,
              "snr pad not aligned, this buf end time %" GST_TIME_FORMAT
              ", need t0 %" GST_TIME_FORMAT ", wait for next turn",
              GST_TIME_ARGS(GST_BUFFER_TIMESTAMP(buf)),
              GST_TIME_ARGS(jointer->t0));
            gst_buffer_unref(buf);
        }
    }
    return all_aligned;
}

static gboolean trigger_jointer_set_next_tstart(GstCollectPads *pads,
                                                TriggerJointer *jointer) {

    TriggerJointerCollectData *data;
    GstBuffer *buf = NULL;
    /* get the tstart from the current postcoh buffer queued in postcoh pad
     */
    buf = gst_collect_pads_peek(jointer->collect,
                                (GstCollectData *)jointer->collect_postcohdata);

    GSList *snrdata;
    if (buf != NULL) { // != if(buf)
        for (snrdata = jointer->collect_snrdata; snrdata;
             snrdata = g_slist_next(snrdata)) {
            data = snrdata->data;
            /* need to account for max time lag of the bypassed ifo */
            data->next_tstart = GST_BUFFER_TIMESTAMP(buf)
                                + GST_BUFFER_DURATION(buf) + data->timelag;
            GST_DEBUG_OBJECT(
              jointer, "t start %" GST_TIME_FORMAT ", t end %" GST_TIME_FORMAT,
              GST_TIME_ARGS(GST_BUFFER_TIMESTAMP(buf)),
              GST_TIME_ARGS(data->next_tstart));
        }
        gst_buffer_unref(buf);
        /* do nothing if it is null buffer */
    }
    return TRUE;
}

/*
 * Check if the end time of the latest snr buffer is later than expected. If
 * yes, we can move on to process.
 */
static gboolean trigger_jointer_need_recollect(GstCollectPads *pads,
                                               TriggerJointer *jointer) {

    GSList *snrdata;
    TriggerJointerCollectData *data;
    GstBuffer *buf = NULL;
    GstClockTime buf_end;
    gboolean need_recollect = FALSE, is_gap;

    for (snrdata = jointer->collect_snrdata; snrdata;
         snrdata = g_slist_next(snrdata)) {
        data = snrdata->data;
        buf  = gst_collect_pads_peek(pads, (GstCollectData *)data);
        if (buf != NULL) { // != if(buf)
            /* zerobuf remove it */
            if (GST_BUFFER_SIZE(buf) == 0) {
                GST_DEBUG_OBJECT(jointer, "bufsize is zero, need to recollect");
                gst_buffer_unref(buf);
                /* discard this buffer in collectpads so it can collect new
                 * one
                 */
                buf = gst_collect_pads_pop(pads, (GstCollectData *)data);
                gst_buffer_unref(buf);
                need_recollect = TRUE;
                continue;
            }
            buf_end = GST_BUFFER_TIMESTAMP(buf) + GST_BUFFER_DURATION(buf);
            if (buf_end < data->next_tstart) {
                /* not enough data */
                /* dump this buffer in collectpads adaptor so it can collect
                 * new one */
                gst_buffer_unref(buf);
                buf    = gst_collect_pads_pop(pads, (GstCollectData *)data);
                is_gap = GST_BUFFER_FLAG_IS_SET(buf, GST_BUFFER_FLAG_GAP)
                           ? TRUE
                           : FALSE;
                add_flag_segment(data, GST_BUFFER_TIMESTAMP(buf), buf_end,
                                 is_gap);
                gst_adapter_push(data->adapter, buf);
                GST_DEBUG_OBJECT(
                  jointer, "not enough data in snr pad, need to recollect");
                need_recollect = TRUE;
                continue;
            } else
                /* enough buffer, proceed to process function */
                GST_DEBUG_OBJECT(jointer,
                                 "enough data in snr pad, proceed to process");
            gst_buffer_unref(buf);
        }
        /* do nothing if it is null buffer */
    }
    return need_recollect;
}

static GstFlowReturn trigger_jointer_append_coinc_snr(TriggerJointer *jointer,
                                                      GstBuffer *postcoh_buf) {

    GSList *snrdata;
    TriggerJointerCollectData *data;
    GstBuffer *buf = NULL;
    COMPLEX_F *snglsnr;
    GstFlowReturn ret = GST_FLOW_OK;
    /* promote the type to double, otherwise it will be interger */
    float exe_dur = ((double)GST_BUFFER_DURATION(postcoh_buf)) / GST_SECOND;
    gint exe_size = 0, one_take_size = 0;
    gboolean is_gap;
    int one_ifo_size = sizeof(gchar) * IFO_LEN, len_ifos = 0, nifo = 0,
        pad_loc = 0;
    LIGOTimeGPS cur_buftime;
    GstClockTime postcoh_buf_ts = GST_BUFFER_TIMESTAMP(postcoh_buf);
    XLALINT8NSToGPS(&cur_buftime, postcoh_buf_ts);

    int tmplt_idx, this_sample;
    float this_sec, this_nano;

    PostcohInspiralTable *trigger;
    PostcohInspiralTable *trigger_start =
      (PostcohInspiralTable *)GST_BUFFER_DATA(postcoh_buf);
    PostcohInspiralTable *trigger_end =
      (PostcohInspiralTable *)(GST_BUFFER_DATA(postcoh_buf)
                               + GST_BUFFER_SIZE(postcoh_buf));

    for (snrdata = jointer->collect_snrdata; snrdata;
         snrdata = g_slist_next(snrdata)) {
        data     = snrdata->data;
        exe_size = round(exe_dur * data->rate * data->bps);
        one_take_size =
          exe_size + data->ntimelag * 2 * data->bps; // bps: bypes per sample
        GST_DEBUG_OBJECT(jointer,
                         "process snr peek size %d, exe_size %d, start time "
                         "%" GST_TIME_FORMAT ", end time %" GST_TIME_FORMAT,
                         one_take_size, exe_size, GST_TIME_ARGS(postcoh_buf_ts),
                         GST_TIME_ARGS(data->next_tstart));

        /* if no triggers, just flush the snrs */
        if (GST_BUFFER_SIZE(postcoh_buf) == 0) {
            gst_adapter_flush(data->adapter, exe_size);
            continue;
        }

        /* get the C pointer to point to the SNR matrix */
        snglsnr = (COMPLEX_F *)gst_adapter_peek(data->adapter, one_take_size);
        /* no enough data in adapter, do nothing */
        if (snglsnr == NULL) continue;

        /*
         * check if this period of data is gap data
         * if gap, flush this data and move on
         */
        is_gap = need_flag_gap(data, postcoh_buf_ts, data->next_tstart);

        if (is_gap) {
            /* flush the SNR matrix from the adapter */
            gst_adapter_flush(data->adapter, exe_size);
            GST_DEBUG_OBJECT(jointer,
                             "the snr buffer is a gap, flush it from adapter");
            continue;
        }

        /* find the coinc snr from tmplt idx
         * and time idx */
        int isample, max_isample = 0;
        COMPLEX_F this_snr;
        float max_abs_snr = 0, this_abs_snr;
        LIGOTimeGPS end_time;
        for (trigger = trigger_start; trigger < trigger_end; trigger++) {
            /* not a gap, extend the trigger field ifos with the new ifo */
            if (trigger->ifos) {
                len_ifos = strlen(trigger->ifos);
                nifo     = len_ifos / IFO_LEN;
                pad_loc  = len_ifos + IFO_LEN;
            }

            /* not a zerolag trigger but an entry
             * just to indicate ifos */
            if (trigger->is_background != FLAG_FOREGROUND) continue;
            max_isample = 0;
            max_abs_snr = 0;
            /* inserting the IFO into the IFO list */
            strncpy(trigger->ifos + len_ifos, data->ifo_name, one_ifo_size);
            trigger->ifos[pad_loc] = '\0';
            /* find the sample corresponding to the end_time of the trigger
             * note adjust the merger end_time to the template end_time */
            this_sec = trigger->end_time.gpsSeconds
                       + trigger->ringdown_dur.gpsSeconds
                       - cur_buftime.gpsSeconds;
            this_nano = trigger->end_time.gpsNanoSeconds
                        + trigger->ringdown_dur.gpsNanoSeconds
                        - cur_buftime.gpsNanoSeconds;
            this_sample =
              round(((double)this_sec + (double)(this_nano) / GST_SECOND)
                    * data->rate);
            if (this_sample < 0 || this_sample >= data->rate) {
                fprintf(
                  stderr,
                  "Search for coinc trigger out of boundary [0, rate) %d\n",
                  this_sample);
                exit(0);
            }
            /* find the tmplt idx of the trigger */
            tmplt_idx = trigger->tmplt_idx;
            /* find the maximum SNR within the window of the triggering time
             */
            for (isample = 0; isample < 2 * data->ntimelag; isample++) {
                this_snr =
                  snglsnr[data->ntmplt * (this_sample + isample) + tmplt_idx];
                this_abs_snr =
                  sqrt(this_snr.re * this_snr.re + this_snr.im * this_snr.im);
                if (this_abs_snr > max_abs_snr) {
                    max_isample = isample;
                    max_abs_snr = this_abs_snr;
                }
            }
            trigger->snglsnr[data->ifo_mapping] = max_abs_snr;
            this_snr =
              snglsnr[data->ntmplt * (this_sample + max_isample) + tmplt_idx];
            trigger->coaphase[data->ifo_mapping] =
              atan2(this_snr.im, this_snr.re);
            end_time = trigger->end_time; // end time from the triggering
                                          // single-ifo trigger
            XLALGPSAdd(&(end_time),
                       (double)(max_isample - data->ntimelag)
                         / data->rate); // adjust for the start
            end_time.gpsSeconds =
              end_time.gpsSeconds
              - trigger->ringdown_dur.gpsSeconds; // adjust for ringdown
            end_time.gpsNanoSeconds =
              end_time.gpsNanoSeconds - trigger->ringdown_dur.gpsNanoSeconds;

            trigger->end_time_sngl[data->ifo_mapping] = end_time;
            trigger->cohsnr = sqrt(trigger->cohsnr * trigger->cohsnr
                                   + max_abs_snr * max_abs_snr);

            /* epoch is the GPS time of the first sample */
            LIGOTimeGPS epoch = trigger->end_time_sngl[data->ifo_mapping];
            g_assert(trigger->autochisq_len % 2 == 1);
            XLALGPSAdd(&epoch, -1.0 / data->rate
                        * (trigger->autochisq_len - 1) / 2);

            // Allocate the memory
            // epoch = epoch
            // f0 = 0
            // deltaT = 1. / postcoh->rate
            // sampleUnits = &lalDimensionlessUnit
            // length = state->autochisq_len
            trigger->snr_series[data->ifo_mapping] =
              XLALCreateCOMPLEX8TimeSeries("snr", &epoch, 0., 1. / data->rate,
                                           &lalDimensionlessUnit,
                                           trigger->autochisq_len);

            this_sample =
              round(((double)epoch.gpsSeconds + (double)(epoch.gpsNanoSeconds) / GST_SECOND)
                    * data->rate);

            // the first data sample
            COMPLEX8 *curr_snglsnr =
              &snglsnr[data->ntmplt * this_sample + tmplt_idx];

            /* FIXME: speedup. Load snglsnr data into snr_series->data->data
             */
            for (int j = 0;
                 j < trigger->snr_series[data->ifo_mapping]->data->length;
                 j++) {
                trigger->snr_series[data->ifo_mapping]->data->data[j] =
                  *curr_snglsnr;
                curr_snglsnr += data->ntmplt;
            }

            GST_DEBUG_OBJECT(
              jointer,
              "new ifos -> %s, this ifo %d, sample %d, tmplt_idx %d,"
              "coinc ifo time %d, %d, max snr.re %f, snr.im %f, snr %f",
              trigger->ifos, data->ifo_mapping, max_isample, tmplt_idx,
              end_time.gpsSeconds, end_time.gpsNanoSeconds, this_snr.re,
              this_snr.im,
              sqrt(this_snr.re * this_snr.re + this_snr.im * this_snr.im));
        }
        gst_adapter_flush(data->adapter, exe_size);
    }
    return ret;
}

static GstFlowReturn trigger_jointer_process(GstCollectPads *pads,
                                             TriggerJointer *jointer) {
    GSList *collectlist;
    TriggerJointerCollectData *data;
    GstBuffer *buf = NULL, *postcoh_buf = NULL;
    GstFlowReturn ret = GST_FLOW_OK;
    gboolean is_gap;
    GstClockTime buf_start, buf_end;

    int i;
    /*
     * first, load the postcoh_buf from the postcoh pad;
     * load each snr adapter with the snr buf from each snr pad
     */
    for (i = 0, collectlist = pads->data; collectlist;
         collectlist = g_slist_next(collectlist), i++) {
        data = collectlist->data;
        buf  = gst_collect_pads_pop(pads, (GstCollectData *)data);

        /* no buffer in SNR pad, do nothing */
        if (!buf && data->is_snr == TRUE) continue;

        /* is a postcoh buffer */
        if (buf && data->is_snr == FALSE) {
            postcoh_buf = buf;
        } else { /* is a snr buffer, add flag segment and push to adapter
                    and */
            is_gap =
              GST_BUFFER_FLAG_IS_SET(buf, GST_BUFFER_FLAG_GAP) ? TRUE : FALSE;
            buf_start = GST_BUFFER_TIMESTAMP(buf);
            buf_end   = buf_start + GST_BUFFER_DURATION(buf);
            add_flag_segment(data, buf_start, buf_end, is_gap);
            gst_adapter_push(data->adapter, buf);
            GST_DEBUG_OBJECT(jointer, "snr buffer pushed to adapter, is gap %d",
                             is_gap);
        }
    }
    /* append coincidence snr from the snr buffer for each postcoh trigger
     */
    ret = trigger_jointer_append_coinc_snr(jointer, postcoh_buf);

    if (ret != GST_FLOW_OK) {
        fprintf(stderr, "failed to append coinc snr");
        return ret;
    }
    /* push the processed table downstream */
    ret = gst_pad_push(jointer->srcpad, postcoh_buf);

    if (ret != GST_FLOW_OK) {
        fprintf(stderr, "failed to push buffer to next element finalsink");
        return ret;
    }

    GST_LOG_OBJECT(jointer, "pushed buffer, result = %s",
                   gst_flow_get_name(ret));
    /* mark to set the next start */
    jointer->is_next_tstart_set = FALSE;
    return ret;
}

static gboolean trigger_jointer_is_EOS(TriggerJointer *jointer) {

    /* check the current postcoh buffer queued in postcoh pad */
    GstBuffer *buf = gst_collect_pads_peek(
      jointer->collect, (GstCollectData *)jointer->collect_postcohdata);

    if (buf == NULL) { // equals !buf ?
        /* no buffer in postcoh pad, mark EOS */
        return TRUE;
    } else
        return FALSE;
}

/* entry function */
static GstFlowReturn collected(GstCollectPads *pads, gpointer user_data) {
    TriggerJointer *jointer = TRIGGER_JOINTER(user_data);

    GstElement *element = GST_ELEMENT(jointer);
    GstClockTime tstart, tend;
    GstFlowReturn ret    = GST_FLOW_OK;
    guint64 offset_start = 0;
    gboolean is_t0_set;

    GST_DEBUG_OBJECT(jointer, "collected");
    /* Make sure that we have enough sink pads. At least 2, one for the
     * postcoh pad, the others for snr pads */
    if (element->numsinkpads < 2) {
        GST_ERROR_OBJECT(
          jointer, "not enough sink pads, 2 required but only %d are present",
          element->numsinkpads < 2);
        return GST_FLOW_ERROR;
    }

    /* check end of stream (EOS) ? */
    if (trigger_jointer_is_EOS(jointer)) {
        ret = gst_pad_push_event(jointer->srcpad, gst_event_new_eos());
        return ret;
    }

    if (!jointer->is_snr_info_set) {
        /* set rate, channels for collected snr pads */
        trigger_jointer_set_snr_info(jointer);
        jointer->is_snr_info_set = TRUE;
    }

    if (!jointer->is_t0_set) {
        /*
         * Initialization. Set the start time t0 from the latest time
         * of any pads, whether the postcoh pad or snr pads. If SNR has the
         * latest time, pass downstream the postcoh buffer and recheck.
         */
        if (!trigger_jointer_get_start_end_time(pads, jointer, &tstart, &tend,
                                                &is_t0_set)) {
            /* bad buffer : one of the buffers is at EOS or invalid
             * timestamp/ offset */
            GST_ERROR_OBJECT(
              jointer, "cannot deduce start timestamp/ offset information");
            return GST_FLOW_ERROR;
        }
        jointer->is_t0_set          = is_t0_set;
        jointer->t0                 = tstart;
        jointer->is_next_tstart_set = FALSE;
        GST_DEBUG_OBJECT(
          jointer, "set the aligned time t0 to %" GST_TIME_FORMAT "%s ",
          GST_TIME_ARGS(jointer->t0), is_t0_set ? "SET" : "NOT SET");
        if (!jointer->is_t0_set) return GST_FLOW_OK;
    }

    if (!jointer->is_all_aligned) {
        /*
         * Align the snr pads to the postcoh pad according to t0.
         * Throw away those buffers from the snr pads whose start timestamps
         * are less than t0. When this condition is satisfied, we can start
         * process the triggers.
         */
        jointer->is_all_aligned =
          trigger_jointer_align_collected(pads, jointer);

    } else {
        if (!jointer->is_next_tstart_set) {
            /* set the stop time (next_tstart) for snr buffer collection
             * using the postcoh buffer */
            jointer->is_next_tstart_set =
              trigger_jointer_set_next_tstart(pads, jointer);
        }
        if (trigger_jointer_need_recollect(pads, jointer))
            /* snr pads do not have enough buffers to cover expected end
             * time, recollect snr buffers */
            return GST_FLOW_OK;
        /* process, append each trigger with coinc snr and push downstream
         */
        ret = trigger_jointer_process(pads, jointer);
    }
    return ret;
}

